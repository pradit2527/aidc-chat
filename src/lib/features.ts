// สวิตช์เปิด/ปิดฟีเจอร์ — อ่านจาก env ตอนเรียก (ไม่ cache ตอน import) จึงตั้งค่าต่างกันได้ต่อเครื่อง/ต่อการรันเทส

/** "1" / "true" / "yes" / "on" (ไม่สนตัวพิมพ์) = เปิด; อย่างอื่นหรือว่าง = ปิด */
export const flagOn = (v: string | undefined) => /^(1|true|yes|on)$/i.test((v ?? "").trim());

/**
 * ระบบแชท (/chat, /admin/chat และการ์ด "ລະບົບແຊັດ" ในหน้าหลักทั้งสองฝั่ง)
 * ผู้ใช้สั่งซ่อนไว้ (19 ต.ค. 2026) ให้เหลือเฉพาะระบบแจ้งปัญหา — โค้ดยังอยู่ครบ เปิดกลับได้ด้วย CHAT_ENABLED=1
 * (ชุดทดสอบ e2e ตั้ง CHAT_ENABLED=1 เพื่อให้เทสของแชทยังรันได้)
 */
export const chatEnabled = () => flagOn(process.env.CHAT_ENABLED);
